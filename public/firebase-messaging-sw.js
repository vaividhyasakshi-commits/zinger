/* This worker and firebase-config.js are served from the same Vite/GitHub Pages base. */
const OFFER_TAG = "zinger-beauty-offer";
let stateQueue = Promise.resolve();
let stateDatabase;

function database() {
  return stateDatabase ||= new Promise((resolve, reject) => {
    const request = indexedDB.open("zinger-push-state", 1);
    request.onupgradeneeded = () => request.result.createObjectStore("settings");
    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error);
  });
}

async function readState() {
  const db = await database();
  return new Promise((resolve, reject) => {
    const request = db.transaction("settings").objectStore("settings").get(self.registration.scope);
    request.onsuccess = () => resolve(request.result || { enabled: false, readAt: 0, revision: 0 });
    request.onerror = () => reject(request.error);
  });
}

async function writeState(state) {
  const db = await database();
  return new Promise((resolve, reject) => {
    const transaction = db.transaction("settings", "readwrite");
    transaction.objectStore("settings").put(state, self.registration.scope);
    transaction.oncomplete = resolve;
    transaction.onerror = () => reject(transaction.error);
  });
}

function serialize(task) {
  const result = stateQueue.then(task);
  stateQueue = result.catch(() => {});
  return result;
}

async function closeOffers() {
  const notifications = await self.registration.getNotifications({ tag: OFFER_TAG });
  notifications.forEach((notification) => notification.close());
}

async function receiveOffer(data) {
  if (!data || !["beauty-offer", "beauty-read"].includes(data.type)) return;
  const state = await readState();
  if (!state.enabled) return;
  const revision = Number(data.revision);
  const readAt = Number(data.readAt || 0);
  if (!Number.isFinite(revision) || revision < state.revision || !Number.isFinite(readAt)) return;
  const count = Number(data.unreadCount);
  const latestAt = Number(data.latestMessageAt || 0);
  if (!Number.isInteger(count) || count < 0 || !Number.isFinite(latestAt)) return;
  state.readAt = Math.max(state.readAt, readAt);
  state.revision = revision;
  if (data.type === "beauty-read" || count === 0) {
    state.eventId = "";
    await writeState(state);
    return closeOffers();
  }
  if (latestAt <= state.readAt || latestAt < Date.now() - 86400000 || state.eventId === data.eventId) return;
  state.eventId = data.eventId;
  await self.registration.showNotification("Beauty Deals • 20% OFF 💗", {
    body: `${count} ${count === 1 ? "product" : "products"} waiting for you! ✨`,
    tag: OFFER_TAG,
    renotify: false,
    silent: true,
    icon: `${self.registration.scope}favicon.svg`,
    data: { url: self.registration.scope },
  });
  await writeState(state);
}

// Custom click behavior must be installed BEFORE loading Firebase.
self.addEventListener("notificationclick", (event) => {
  event.stopImmediatePropagation();
  event.notification.close();
  const url = self.registration.scope;
  event.waitUntil(self.clients.matchAll({ type: "window", includeUncontrolled: true }).then(async (windows) => {
    for (const client of windows) if (client.url.startsWith(url)) return client.focus();
    return self.clients.openWindow(url);
  }));
});

self.addEventListener("install", (event) => event.waitUntil(self.skipWaiting()));
self.addEventListener("activate", (event) => event.waitUntil(self.clients.claim()));
self.addEventListener("message", (event) => {
  const data = event.data;
  if (!data?.type?.startsWith("ZINGER_")) return;
  if (!event.source?.url?.startsWith(self.registration.scope)) return;
  const task = serialize(async () => {
    if (data.type === "ZINGER_PUSH_STATE") {
      const state = await readState();
      state.enabled = data.enabled === true;
      if (!state.enabled) state.eventId = "";
      await writeState(state);
      if (!state.enabled) await closeOffers();
    } else if (data.type === "ZINGER_READ") {
      const state = await readState();
      const at = Number(data.readAt);
      if (Number.isFinite(at)) state.readAt = Math.max(state.readAt, at);
      state.eventId = "";
      await writeState(state);
      await closeOffers();
    } else if (data.type === "ZINGER_PUSH") {
      await receiveOffer(data.payload);
    }
  });
  event.waitUntil(task.then(
    () => event.ports[0]?.postMessage({ ok: true }),
    () => event.ports[0]?.postMessage({ ok: false }),
  ));
});

// Generated by Vite from an allowlist of PUBLIC Firebase web fields only.
importScripts("./firebase-config.js");
importScripts(
  `https://www.gstatic.com/firebasejs/${self.ZINGER_FIREBASE_SDK_VERSION}/firebase-app-compat.js`,
  `https://www.gstatic.com/firebasejs/${self.ZINGER_FIREBASE_SDK_VERSION}/firebase-messaging-compat.js`,
);
firebase.initializeApp(self.ZINGER_FIREBASE_CONFIG);
firebase.messaging().onBackgroundMessage((payload) => serialize(() => receiveOffer(payload.data)));
